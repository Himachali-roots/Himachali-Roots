-- 3) If the table already existed with extra "required" columns the form does not send, make them optional
do $$
declare c record;
begin
  for c in
    select column_name
    from information_schema.columns
    where table_schema = 'public' and table_name = 'submissions'
      and is_nullable = 'NO' and column_default is null and is_identity = 'NO'
      and column_name not in (
        select a.attname
        from pg_index i
        join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any (i.indkey)
        where i.indrelid = 'public.submissions'::regclass and i.indisprimary
      )
  loop
    execute format('alter table public.submissions alter column %I drop not null', c.column_name);
  end loop;
end $$;

-- 4) Permissions: visitors may read published entries and send submissions (never read them)
alter table "Entries" enable row level security;
drop policy if exists "Public can read entries" on "Entries";
create policy "Public can read entries"
  on "Entries" for select
  to anon, authenticated
  using (status is null or lower(status) in ('approved', 'published', 'live'));
grant select on "Entries" to anon, authenticated;

alter table public.submissions enable row level security;
drop policy if exists "Public can submit" on public.submissions;
create policy "Public can submit"
  on public.submissions for insert
  to anon, authenticated
  with check (true);
grant insert on public.submissions to anon, authenticated;

-- 5) Storage: a new public bucket for pictures (max 10 MB), and permission to upload recordings and pictures
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('Pictures', 'Pictures', true, 10485760, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update
  set public = true, file_size_limit = 10485760, allowed_mime_types = array['image/jpeg', 'image/png', 'image/webp'];

drop policy if exists "Public can upload submission pictures" on storage.objects;
create policy "Public can upload submission pictures"
  on storage.objects for insert
  to anon, authenticated
  with check (bucket_id = 'Pictures' and (storage.foldername(name))[1] = 'submissions');

drop policy if exists "Public can upload submission recordings" on storage.objects;
create policy "Public can upload submission recordings"
  on storage.objects for insert
  to anon, authenticated
  with check (bucket_id = 'Audio-files' and (storage.foldername(name))[1] = 'submissions');
